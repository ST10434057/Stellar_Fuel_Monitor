package za.co.stellar.fuelmonitor.localization

import androidx.compose.runtime.Composable
import androidx.compose.runtime.staticCompositionLocalOf

enum class AppLanguage(val displayName: String, val nativeName: String) {
    ENGLISH("English", "English"),
    AFRIKAANS("Afrikaans", "Afrikaans"),
    ISIZULU("isiZulu", "isiZulu");

    companion object {
        fun fromStored(value: String): AppLanguage = entries.firstOrNull {
            it.displayName.equals(value, true) || it.name.equals(value, true)
        } ?: ENGLISH
    }
}

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.ENGLISH }

/**
 * Lightweight runtime localisation for Compose. Business data returned by the API is intentionally
 * left unchanged, while navigation, actions, forms, state messages and common labels are translated.
 */
@Composable
fun tr(english: String): String = translate(english, LocalAppLanguage.current)

fun translate(english: String, language: AppLanguage): String {
    if (language == AppLanguage.ENGLISH) return english
    val values = when (language) {
        AppLanguage.AFRIKAANS -> af
        AppLanguage.ISIZULU -> zu
        AppLanguage.ENGLISH -> emptyMap()
    }
    return values[english] ?: english
}

